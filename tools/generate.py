#!/usr/bin/env python3
"""Regenerate the patches, the category pages, and the generated blocks of this repository.

    python3 tools/generate.py --fork PATH [--base REF] [--head REF] [--check]

PATH is a clone of the fork. The commits in BASE..HEAD (default upstream/trunk..main) are the patch
series. Commit subjects start with "[TRACKER #NUM]", which assigns each commit to the entry
tickets/TRACKER/NUM.md. An entry with a patch_of field takes the commits of the ticket that the
field names. With --check nothing is written and the exit status is 1 when a file is out
of date or when entries and commits do not match.
"""
import argparse
import json
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# key: (page title, text under the title)
CATEGORIES = {
    "fixed-upstream": (
        "Already fixed in trunk",
        "The behavior reported in the ticket does not occur in trunk. The revision in which it was "
        "fixed is given in the entry when that revision was identified.",
    ),
    "not-reproducible": (
        "Not reproducible",
        "The behavior reported in the ticket could not be reproduced, and a revision with a fix "
        "for it was not identified. What was tried is listed in the entry.",
    ),
    "duplicate": (
        "Duplicates",
        "The same problem is already reported in another ticket.",
    ),
    "no-action": (
        "No action recommended",
        "The behavior reported in the ticket is correct, or the request conflicts with the C "
        "standard or with the behavior described in SDCC's documentation. The reason is given in "
        "the entry.",
    ),
    "needs-info": (
        "Information needed from the reporter",
        "The ticket cannot be judged without something that only the reporter has. What is missing "
        "is stated in the entry.",
    ),
    "fix-trivial": (
        "Trivial fixes",
        "The source change is a few lines in one place. The diff is in the entry.",
    ),
    "fix": (
        "Fixes",
        "The cause is identified and the change is confined to it. The patch includes a regression "
        "test that fails without the change.",
    ),
    "fix-decision": (
        "Fixes that need a decision",
        "The fork has a patch, and the patch contains a choice that a maintainer should confirm or "
        "change. The choice and the alternatives are stated in the entry.",
    ),
    "unresolved": (
        "Analyzed, not fixed",
        "The problem is reproduced or located, and the fork does not have a patch for it. What is "
        "known, and what a fix would involve, is stated in the entry.",
    ),
    "unreported": (
        "Problems without a ticket",
        "Problems found during this work that do not have SourceForge tickets. The entries have "
        "reproducers.",
    ),
}
FIX_CATEGORIES = ("fix-trivial", "fix", "fix-decision")
TRACKER_NAMES = {
    "bugs": "bugs",
    "feature-requests": "feature request",
    "patches": "patches",
    "support-requests": "support request",
    "local": "local",
}
BEGIN = "<!-- generated by tools/generate.py -->"
END = "<!-- end of generated block -->"


def git(fork, *args, env=None, check=True):
    r = subprocess.run(["git", "-C", fork, *args], capture_output=True, text=True, env=env)
    if check and r.returncode:
        sys.exit("git %s failed:\n%s" % (" ".join(args), r.stderr))
    return r


def read_entry(path):
    text = open(path, encoding="utf-8").read()
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        sys.exit("%s: no front matter" % path)
    fields = {}
    for line in m.group(1).splitlines():
        key, sep, value = line.partition(":")
        if not sep:
            sys.exit("%s: bad front matter line: %s" % (path, line))
        value = value.strip()
        if len(value) > 1 and value[0] == value[-1] == '"':
            value = value[1:-1]
        fields[key.strip()] = value
    rest = text[m.end():]
    if BEGIN in rest and END in rest:
        rest = rest.split(END, 1)[1]
    return fields, m.group(0), rest.lstrip("\n")


def load_entries():
    entries = {}
    top = os.path.join(ROOT, "tickets")
    for tracker in sorted(os.listdir(top)):
        for name in sorted(os.listdir(os.path.join(top, tracker))):
            if not name.endswith(".md"):
                continue
            path = os.path.join(top, tracker, name)
            fields, front, body = read_entry(path)
            key = "%s/%s" % (tracker, name[:-3])
            for need in ("ticket", "title", "category", "evidence", "checked", "action"):
                if need not in fields:
                    sys.exit("%s: front matter lacks '%s'" % (path, need))
            if fields["ticket"] != key:
                sys.exit("%s: ticket field is %s" % (path, fields["ticket"]))
            if fields["category"] not in CATEGORIES:
                sys.exit("%s: unknown category %s" % (path, fields["category"]))
            if fields["evidence"] not in ("tested", "read"):
                sys.exit("%s: evidence must be tested or read" % path)
            entries[key] = {"fields": fields, "front": front, "body": body, "path": path,
                            "commits": []}
    return entries


def sort_key(key):
    tracker, num = key.split("/")
    return (list(TRACKER_NAMES).index(tracker), int(num))


def label(key):
    tracker, num = key.split("/")
    if tracker == "local":
        return "local %s" % num
    return "%s #%s" % (tracker, num.lstrip("0"))


def ticket_url(config, key):
    tracker, num = key.split("/")
    if tracker == "local":
        return None
    return config["ticket_url"].format(tracker=tracker, num=num)


def series(fork, base, head):
    out = git(fork, "log", "--reverse", "--format=%H%x09%s", "%s..%s" % (base, head)).stdout
    commits = []
    for line in out.splitlines():
        sha, subject = line.split("\t", 1)
        m = re.match(r"\[([a-z-]+) #(\d+)\]", subject)
        key = None
        if m:
            width = 4 if m.group(1) == "local" else 0
            key = "%s/%s" % (m.group(1), m.group(2).zfill(width))
        files = git(fork, "show", "--format=", "--name-only", sha).stdout.split()
        commits.append({"sha": sha, "subject": subject, "key": key, "files": files})
    return commits


def name_patches(commits):
    count = {}
    for c in commits:
        count[c["key"]] = count.get(c["key"], 0) + 1
    seen = {}
    for c in commits:
        stem = c["key"].replace("/", "-")
        if count[c["key"]] > 1:
            seen[c["key"]] = seen.get(c["key"], 0) + 1
            stem += "-%d" % seen[c["key"]]
        c["patch"] = stem + ".patch"


def applies(fork, base, texts):
    """True when the patches apply in order to the tree of base."""
    with tempfile.TemporaryDirectory() as tmp:
        env = dict(os.environ, GIT_INDEX_FILE=os.path.join(tmp, "index"))
        git(fork, "read-tree", base, env=env)
        for n, text in enumerate(texts):
            path = os.path.join(tmp, "%d.patch" % n)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            if git(fork, "apply", "--cached", path, env=env, check=False).returncode:
                return False
    return True


def find_requirements(fork, base, commits):
    """For each commit, the earlier patches that it needs before it applies to base."""
    for i, c in enumerate(commits):
        c["needs"] = []
        if applies(fork, base, [c["text"]]):
            continue
        files = set(c["files"])
        need = []
        for j in range(i - 1, -1, -1):
            if files & set(commits[j]["files"]):
                need.insert(0, j)
                files |= set(commits[j]["files"])
        if not applies(fork, base, [commits[j]["text"] for j in need] + [c["text"]]):
            need = list(range(i))
        for j in list(need):
            trial = [k for k in need if k != j]
            if applies(fork, base, [commits[k]["text"] for k in trial] + [c["text"]]):
                need = trial
        c["needs"] = [commits[j]["patch"] for j in need]


def source_diff(fork, sha):
    files = git(fork, "show", "--format=", "--name-only", sha).stdout.split()
    keep = [f for f in files if not f.startswith(("support/regression/", "support/valdiag/"))]
    if not keep:
        return ""
    return git(fork, "show", "--format=", sha, "--", *keep).stdout.strip("\n")


def entry_block(config, key, entry, rev, up):
    f = entry["fields"]
    title, _ = CATEGORIES[f["category"]]
    lines = [BEGIN, "# %s: %s" % (label(key), f["title"]), ""]
    url = ticket_url(config, key)
    if url:
        lines.append("- Ticket: %s" % url)
    lines.append("- Category: [%s](%s%s.md)" % (title, up, f["category"]))
    how = "tested on" if f["evidence"] == "tested" else "judged by reading, against"
    lines.append("- Evidence: %s %s" % (how, f["checked"]))
    lines.append("- Recommended action: %s" % f["action"])
    for c in entry["commits"]:
        text = "- Patch: [%s](%spatches/%s)" % (c["patch"], up, c["patch"])
        if config.get("fork_url"):
            text += ", commit [`%s`](%s/commit/%s)" % (c["sha"][:9], config["fork_url"], c["sha"])
        if c["needs"]:
            text += ". Apply after %s." % ", ".join("`%s`" % n for n in c["needs"])
        else:
            text += ". Applies to %s without the other patches." % rev
        lines.append(text)
    if f["category"] == "fix-trivial":
        for c in entry["commits"]:
            diff = c["source_diff"]
            if diff:
                lines += ["", "```diff", diff, "```"]
    lines += [END, ""]
    return "\n".join(lines)


def category_page(config, cat, entries):
    title, intro = CATEGORIES[cat]
    keys = sorted((k for k in entries if entries[k]["fields"]["category"] == cat), key=sort_key)
    lines = ["# %s" % title, "", intro, ""]
    if not keys:
        lines.append("This category is empty.")
        return "\n".join(lines) + "\n"
    has_patch = cat in FIX_CATEGORIES
    head = ["Ticket", "Entry", "Recommended action", "Evidence"] + (["Patch"] if has_patch else [])
    lines.append("| " + " | ".join(head) + " |")
    lines.append("|" + "---|" * len(head))
    for k in keys:
        e = entries[k]
        f = e["fields"]
        url = ticket_url(config, k)
        cells = [
            "[%s](%s)" % (label(k), url) if url else label(k),
            "[%s](tickets/%s.md)" % (f["title"].replace("|", "\\|"), k),
            f["action"].replace("|", "\\|"),
            "%s, %s" % (f["evidence"], f["checked"]),
        ]
        if has_patch:
            cells.append(", ".join("[%s](patches/%s)" % (c["patch"], c["patch"])
                                   for c in e["commits"]))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def readme_block(config, entries, commits, rev, head_sha):
    lines = [BEGIN, ""]
    lines.append("The fork is trunk %s plus %d commits." % (rev, len(commits)))
    if config.get("fork_url"):
        lines.append("Its head is [`%s`](%s/commit/%s)." % (head_sha[:9], config["fork_url"],
                                                          head_sha))
    else:
        lines.append("Its head is `%s`." % head_sha[:9])
    lines += ["", "| Category | Entries |", "|---|---|"]
    for cat, (title, _) in CATEGORIES.items():
        n = sum(1 for e in entries.values() if e["fields"]["category"] == cat)
        lines.append("| [%s](%s.md) | %d |" % (title, cat, n))
    lines += ["", END]
    return "\n".join(lines)


class Output:
    def __init__(self, check):
        self.check = check
        self.stale = []

    def write(self, path, text):
        old = None
        if os.path.exists(path):
            old = open(path, encoding="utf-8").read()
        if old == text:
            return
        self.stale.append(os.path.relpath(path, ROOT))
        if not self.check:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--fork", required=True, help="path of a clone of the fork")
    ap.add_argument("--base", default="upstream/trunk")
    ap.add_argument("--head", default="main")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    config = json.load(open(os.path.join(ROOT, "config.json"), encoding="utf-8"))
    entries = load_entries()
    commits = series(args.fork, args.base, args.head)
    base_msg = git(args.fork, "log", "-n", "1", "--format=%B", args.base).stdout
    m = re.search(r"git-svn-id: \S+@(\d+)", base_msg)
    rev = "r" + m.group(1) if m else git(args.fork, "rev-parse", "--short", args.base).stdout.strip()
    head_sha = git(args.fork, "rev-parse", args.head).stdout.strip()

    problems = []
    for c in commits:
        if c["key"] is None:
            problems.append("commit %s has no [tracker #num] prefix: %s" % (c["sha"][:9], c["subject"]))
            c["key"] = "local/%s" % c["sha"][:9]
        elif c["key"] not in entries:
            problems.append("commit %s: no entry tickets/%s.md" % (c["sha"][:9], c["key"]))
    name_patches(commits)
    for c in commits:
        c["text"] = git(args.fork, "format-patch", "--stdout", "--zero-commit", "--no-signature",
                        "-1", c["sha"]).stdout
        c["source_diff"] = source_diff(args.fork, c["sha"])
        if c["key"] in entries:
            entries[c["key"]]["commits"].append(c)
    find_requirements(args.fork, args.base, commits)
    for k, e in entries.items():
        other = e["fields"].get("patch_of")
        if other:
            e["commits"] = [c for c in commits if c["key"] == other]
        need = e["fields"].get("requires")
        for c in e["commits"]:
            for d in commits:
                if need and d["key"] == need and d["patch"] not in c["needs"] and d is not c:
                    c["needs"] = c["needs"] + [d["patch"]]
    for k, e in entries.items():
        is_fix = e["fields"]["category"] in FIX_CATEGORIES
        if is_fix and not e["commits"]:
            problems.append("tickets/%s.md is in a fix category and has no commit" % k)
        if e["commits"] and not is_fix:
            problems.append("tickets/%s.md has commits and category %s" % (k, e["fields"]["category"]))

    out = Output(args.check)
    pdir = os.path.join(ROOT, "patches")
    for c in commits:
        out.write(os.path.join(pdir, c["patch"]), c["text"])
    out.write(os.path.join(pdir, "series"), "".join(c["patch"] + "\n" for c in commits))
    known = {c["patch"] for c in commits} | {"series"}
    for name in sorted(os.listdir(pdir)):
        if name not in known:
            problems.append("patches/%s is not in the series; remove it" % name)
    for k, e in entries.items():
        block = entry_block(config, k, e, rev, "../../")
        out.write(e["path"], e["front"] + block + "\n" + e["body"])
    for cat in CATEGORIES:
        out.write(os.path.join(ROOT, cat + ".md"), category_page(config, cat, entries))
    readme = os.path.join(ROOT, "README.md")
    text = open(readme, encoding="utf-8").read()
    if BEGIN not in text or END not in text:
        sys.exit("README.md lacks the generated block markers")
    before, rest = text.split(BEGIN, 1)
    after = rest.split(END, 1)[1]
    out.write(readme, before + readme_block(config, entries, commits, rev, head_sha) + after)

    for p in problems:
        print("PROBLEM: " + p)
    for s in out.stale:
        print(("out of date: " if args.check else "wrote ") + s)
    print("%d entries, %d commits on %s" % (len(entries), len(commits), rev))
    sys.exit(1 if problems or (args.check and out.stale) else 0)


if __name__ == "__main__":
    main()
